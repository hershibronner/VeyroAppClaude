// PDF rendering (pdfkit) for generated documents and signed copies with a signature certificate page.
import PDFDocument from 'pdfkit';

function toBuffer(build: (doc: PDFKit.PDFDocument) => void): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'LETTER', margin: 64, info: { Producer: 'VeyroApp', Creator: 'VeyroApp e-signature' } });
    const chunks: Buffer[] = [];
    doc.on('data', c => chunks.push(c as Buffer));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    try { build(doc); doc.end(); } catch (e) { reject(e); }
  });
}

function header(doc: PDFKit.PDFDocument, orgName: string, title: string) {
  doc.fillColor('#0A0E16').font('Helvetica-Bold').fontSize(11).text(orgName, { continued: false });
  doc.moveDown(0.2).strokeColor('#E5E7EB').lineWidth(1).moveTo(64, doc.y).lineTo(548, doc.y).stroke();
  doc.moveDown(1).font('Helvetica-Bold').fontSize(18).text(title);
  doc.moveDown(0.8);
}
function body(doc: PDFKit.PDFDocument, text: string) {
  doc.font('Helvetica').fontSize(11).fillColor('#111827');
  for (const para of text.split(/\n{2,}/)) {
    const lines = para.split('\n');
    const isHeading = lines.length === 1 && /^[A-Z0-9 &'’\-]{6,}$/.test(lines[0].trim());
    if (isHeading) doc.font('Helvetica-Bold').fontSize(12).text(lines[0].trim()).font('Helvetica').fontSize(11);
    else doc.text(lines.join('\n'), { align: 'left', lineGap: 3 });
    doc.moveDown(0.7);
  }
}

/** Unsigned document generated from a template. */
export function renderDocumentPdf(opts: { orgName: string; title: string; body: string; footer?: string }): Promise<Buffer> {
  return toBuffer(doc => {
    header(doc, opts.orgName, opts.title);
    body(doc, opts.body);
    doc.moveDown(2).font('Helvetica').fontSize(9).fillColor('#6B7280').text(opts.footer ?? `Generated by VeyroApp on ${new Date().toISOString().slice(0, 10)}.`);
  });
}

export interface Certificate { requestId: string; documentTitle: string; signerName: string; signerEmail: string; typedName: string; signedAt: string; ip: string; userAgent: string; sentAt: string; viewedAt: string | null; contentSha256: string; orgName: string }

/** Signed copy: original content + signature block, then a signature certificate page. */
export function renderSignedPdf(opts: { orgName: string; title: string; body: string; signaturePng: Buffer; cert: Certificate }): Promise<Buffer> {
  return toBuffer(doc => {
    header(doc, opts.orgName, opts.title);
    body(doc, opts.body);
    if (doc.y > 600) doc.addPage();
    doc.moveDown(1.5).font('Helvetica-Bold').fontSize(11).fillColor('#0A0E16').text('Signature');
    doc.moveDown(0.4);
    const y = doc.y;
    doc.roundedRect(64, y, 260, 96, 8).strokeColor('#D1D5DB').stroke();
    try { doc.image(opts.signaturePng, 74, y + 8, { fit: [240, 64] }); } catch { doc.font('Helvetica-Oblique').fontSize(20).text(opts.cert.typedName, 74, y + 28); }
    doc.font('Helvetica').fontSize(9).fillColor('#374151').text(`${opts.cert.typedName} · ${opts.cert.signedAt.replace('T', ' ').slice(0, 19)} UTC`, 74, y + 76);
    doc.text('', 64, y + 110);

    doc.addPage();
    doc.fillColor('#0A0E16').font('Helvetica-Bold').fontSize(16).text('Signature certificate');
    doc.moveDown(0.3).font('Helvetica').fontSize(10).fillColor('#6B7280').text('This page records how and when this document was signed electronically through VeyroApp.');
    doc.moveDown(1);
    const rows: [string, string][] = [
      ['Document', opts.cert.documentTitle], ['Issued by', opts.cert.orgName], ['Request ID', opts.cert.requestId],
      ['Signer', `${opts.cert.signerName} <${opts.cert.signerEmail}>`], ['Typed name', opts.cert.typedName],
      ['Sent', opts.cert.sentAt], ['First viewed', opts.cert.viewedAt ?? '—'], ['Signed', opts.cert.signedAt],
      ['Signer IP address', opts.cert.ip], ['User agent', opts.cert.userAgent.slice(0, 160)], ['Content SHA-256', opts.cert.contentSha256],
    ];
    for (const [k, v] of rows) {
      const top = doc.y;
      doc.font('Helvetica-Bold').fontSize(10).fillColor('#374151').text(k, 64, top, { width: 130 });
      doc.font('Helvetica').fontSize(10).fillColor('#111827').text(v, 200, top, { width: 348 });
      doc.moveDown(0.6);
    }
    doc.moveDown(1);
    try { doc.image(opts.signaturePng, 64, doc.y, { fit: [200, 60] }); doc.moveDown(4.5); } catch { /* signature image optional */ }
    doc.font('Helvetica').fontSize(8.5).fillColor('#6B7280').text('The signer agreed to sign electronically. The content hash above identifies the exact text that was presented and signed.', 64);
  });
}
